package main

import (
	"go/ast"
	"go/token"
	"strings"
	"text/template"
)

// collectDecl records doc comments of interfaces ("Name") and their methods
// ("Name.Method").
func collectDecl(d ast.Decl, out map[string]string) {
	gd, ok := d.(*ast.GenDecl)
	if !ok || gd.Tok != token.TYPE {
		return
	}
	for _, spec := range gd.Specs {
		ts := spec.(*ast.TypeSpec)
		doc := ts.Doc
		if doc == nil && len(gd.Specs) == 1 {
			doc = gd.Doc
		}
		if doc != nil {
			out[ts.Name.Name] = doc.Text() + rawDirectives(doc)
		}
		it, ok := ts.Type.(*ast.InterfaceType)
		if !ok {
			continue
		}
		for _, f := range it.Methods.List {
			if len(f.Names) == 0 || f.Doc == nil {
				continue
			}
			out[ts.Name.Name+"."+f.Names[0].Name] = f.Doc.Text() + rawDirectives(f.Doc)
		}
	}
}

// rawDirectives returns //kakarot: lines, which CommentGroup.Text drops
// because directives have no space after //.
func rawDirectives(g *ast.CommentGroup) string {
	var b strings.Builder
	for _, c := range g.List {
		if rest, ok := strings.CutPrefix(c.Text, "//kakarot:"); ok {
			b.WriteString("\nkakarot:" + rest)
		}
	}
	return b.String()
}

var funcs = template.FuncMap{
	"lower": strings.ToLower,
}

var endpointsTmpl = template.Must(template.New("ep").Funcs(funcs).Parse(`// Code generated by kakarot gen. DO NOT EDIT.

// Package endpoint turns service methods into typed endpoints and streams.
package endpoint

import (
{{- range .Imports}}
	"{{.}}"
{{- end}}
)
{{range $s := .Services}}
// {{$s.Short}}Endpoints holds one typed endpoint or stream per {{$s.Name}} method.
type {{$s.Short}}Endpoints struct {
{{- range $s.Methods}}
	{{.Name}} kakarot.{{.Kind}}[{{.In}}, {{.Out}}]
{{- end}}
}

// Make{{$s.Short}}Endpoints builds the endpoints. Requests with a Validate
// method are wrapped with middleware.Validated.
func Make{{$s.Short}}Endpoints(svc {{$.SvcName}}.{{$s.Name}}) {{$s.Short}}Endpoints {
	return {{$s.Short}}Endpoints{
{{- range $s.Methods}}
		{{.Name}}: {{if .Validate}}middleware.Validated(svc.{{.Name}}){{else}}svc.{{.Name}}{{end}},
{{- end}}
	}
}
{{end}}`))

var httpTmpl = template.Must(template.New("http").Funcs(funcs).Parse(`// Code generated by kakarot gen. DO NOT EDIT.

// Package transport binds the generated endpoints to HTTP.
package transport

import (
{{- range .Imports}}
	"{{.}}"
{{- end}}
)
{{range $s := .Services}}
// Register{{$s.Short}}HTTP mounts every //kakarot:http method of {{$s.Name}}.
// mws are shared endpoint middleware for the whole group.
func Register{{$s.Short}}HTTP(r *httpx.Router, eps endpoint.{{$s.Short}}Endpoints, mws ...kakarot.Middleware) {
	g := r.Group({{printf "%q" $s.Group}}, mws...)
{{- range $s.Methods}}{{if .HTTP}}
{{- if eq .Kind "Endpoint"}}
	g.Handle({{printf "%q" .HTTP}}, eps.{{.Name}}, httpx.Name("{{.Name}}"))
{{- else if eq .Kind "ServerStream"}}
	g.Stream({{printf "%q" .HTTP}}, eps.{{.Name}}, httpx.Name("{{.Name}}"))
{{- else if eq .Kind "ClientStream"}}
	g.Upload({{printf "%q" .HTTP}}, eps.{{.Name}}, httpx.Name("{{.Name}}"))
{{- else}}
	wsx.Handle(g, {{printf "%q" .HTTP}}, eps.{{.Name}}, wsx.Options{Name: "{{.Name}}"})
{{- end}}{{end}}{{end}}
}
{{end}}`))
