// collectDecl records doc comments of interfaces ("Name") and their methods
// ("Name.Method").
func collectDecl(d ast.Decl, out map[string]string) {
	gd, ok := d.(*ast.GenDecl)
	if !ok || gd.Tok != token.TYPE {
		return
	}
	for _, spec := range gd.Specs {
		ts := spec.(*ast.TypeSpec)
		doc := ts.Doc
		if doc == nil && len(gd.Specs) == 1 {
			doc = gd.Doc
		}
		if doc != nil {
			out[ts.Name.Name] = doc.Text() + rawDirectives(doc)
		}
		it, ok := ts.Type.(*ast.InterfaceType)
		if !ok {
			continue
		}
		for _, f := range it.Methods.List {
			if len(f.Names) == 0 || f.Doc == nil {
				continue
			}
			out[ts.Name.Name+"."+f.Names[0].Name] = f.Doc.Text() + rawDirectives(f.Doc)
		}
	}
}

// rawDirectives returns //kakarot: lines, which CommentGroup.Text drops
// because directives have no space after //.
func rawDirectives(g *ast.CommentGroup) string {
	var b strings.Builder
	for _, c := range g.List {
		if rest, ok := strings.CutPrefix(c.Text, "//kakarot:"); ok {
			b.WriteString("\nkakarot:" + rest)
		}
	}
	return b.String()
}

